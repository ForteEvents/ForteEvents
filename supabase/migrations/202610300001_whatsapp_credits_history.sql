-- ForteEvents WhatsApp customer credits and history
-- Run once in Supabase SQL Editor before deploying/enabling WhatsApp sending.

alter table public.profiles
  add column if not exists whatsapp_balance bigint not null default 0;

create table if not exists public.whatsapp_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  recipient text not null,
  message text not null,
  status text not null check (status in ('sent', 'failed', 'pending')),
  error_message text,
  provider_message_id text,
  sent_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists whatsapp_history_user_created_idx
  on public.whatsapp_history (user_id, created_at desc);

alter table public.whatsapp_history enable row level security;

drop policy if exists "Customers can read own WhatsApp history"
  on public.whatsapp_history;

create policy "Customers can read own WhatsApp history"
  on public.whatsapp_history
  for select
  to authenticated
  using (auth.uid() = user_id);

grant select on public.whatsapp_history to authenticated;
grant all on public.whatsapp_history to service_role;
grant usage, select on sequence public.whatsapp_history_id_seq to service_role;

create or replace function public.reserve_whatsapp_credit(p_user_id uuid)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_balance bigint;
begin
  update public.profiles
  set whatsapp_balance = whatsapp_balance - 1,
      updated_at = now()
  where id = p_user_id
    and whatsapp_balance >= 1
  returning whatsapp_balance into new_balance;

  return new_balance;
end;
$$;

create or replace function public.refund_whatsapp_credit(p_user_id uuid)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_balance bigint;
begin
  update public.profiles
  set whatsapp_balance = whatsapp_balance + 1,
      updated_at = now()
  where id = p_user_id
  returning whatsapp_balance into new_balance;

  return new_balance;
end;
$$;

create or replace function public.add_whatsapp_credits(p_user_id uuid, p_amount bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  new_balance bigint;
begin
  if p_amount is null or p_amount <= 0 or p_amount > 1000000 then
    raise exception 'Invalid WhatsApp credit amount';
  end if;

  update public.profiles
  set whatsapp_balance = whatsapp_balance + p_amount,
      updated_at = now()
  where id = p_user_id
  returning whatsapp_balance into new_balance;

  if new_balance is null then
    raise exception 'Customer profile not found';
  end if;

  return new_balance;
end;
$$;

revoke all on function public.reserve_whatsapp_credit(uuid) from public, anon, authenticated;
revoke all on function public.refund_whatsapp_credit(uuid) from public, anon, authenticated;
revoke all on function public.add_whatsapp_credits(uuid, bigint) from public, anon, authenticated;
grant execute on function public.reserve_whatsapp_credit(uuid) to service_role;
grant execute on function public.refund_whatsapp_credit(uuid) to service_role;
grant execute on function public.add_whatsapp_credits(uuid, bigint) to service_role;
