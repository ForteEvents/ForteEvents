-- ForteEvents: persistent SMS contact groups
-- Run this migration in Supabase SQL Editor.
create table if not exists public.sms_contact_groups (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  created_at timestamptz not null default now(),
  constraint sms_contact_groups_user_name_unique unique (user_id, name)
);

insert into public.sms_contact_groups (user_id, name)
select distinct user_id, coalesce(nullif(trim(group_name), ''), 'Contacts Zangu')
from public.sms_contacts
on conflict (user_id, name) do nothing;

-- Ensure every existing customer has the default group, including customers
-- whose contact list is currently empty.
insert into public.sms_contact_groups (user_id, name)
select id, 'Contacts Zangu' from auth.users
on conflict (user_id, name) do nothing;

create or replace function public.rename_sms_contact_group(
  p_user_id uuid,
  p_old_name text,
  p_new_name text
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  changed_count integer := 0;
begin
  if p_old_name is null or trim(p_old_name) = '' or p_new_name is null or trim(p_new_name) = '' then
    raise exception 'Jina la kundi haliwezi kuwa tupu.';
  end if;
  if p_old_name = p_new_name then return 0; end if;
  if exists (
    select 1 from public.sms_contact_groups
    where user_id = p_user_id and name = trim(p_new_name)
  ) then
    raise exception 'Kundi lenye jina hilo tayari lipo.';
  end if;
  update public.sms_contacts
  set group_name = trim(p_new_name)
  where user_id = p_user_id and coalesce(nullif(trim(group_name), ''), 'Contacts Zangu') = trim(p_old_name);
  get diagnostics changed_count = row_count;
  update public.sms_contact_groups
  set name = trim(p_new_name)
  where user_id = p_user_id and name = trim(p_old_name);
  if not found then
    raise exception 'Kundi halijapatikana.';
  end if;
  return changed_count;
end;
$$;

revoke all on function public.rename_sms_contact_group(uuid, text, text) from public;
grant execute on function public.rename_sms_contact_group(uuid, text, text) to service_role;

grant select, insert, update, delete on public.sms_contact_groups to service_role;
grant usage, select on sequence public.sms_contact_groups_id_seq to service_role;
